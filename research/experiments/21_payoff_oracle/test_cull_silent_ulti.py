"""Airtight: does the EV_MULTI dominance cull EVER change a multi value when
silent_ulti is active? If it pruned a silent-ulti-relevant move, some legal
move's minimax value would differ cull-on vs cull-off.

At every endgame ply where the current mover holds the trump-7 (soloist OR a
defender), we solve_root TWICE — cull on (_cull_parti_blocks) and cull off
(_cull_noop) — and compare the value of every legal move. solve_root applies no
cull at the root but the full cull in the deep search, so this tests it
end-to-end. The value-equivalence must hold on ANY valid 7-holding position, so
positions are generated by a cheap RANDOM walk that never voluntarily plays the
trump-7 (keeping it held deep into the endgame) — no per-ply solving.

Deals: ulti-biased (soloist holds 7) + parti filtered to a defender holding 7,
so both seats are exercised as the 7-holding mover.

Usage: python test_cull_silent_ulti.py [N_EACH] [MAX_CARDS]
"""
import random, sys, time
from pathlib import Path
sys.path.insert(0, '/Users/milansimity/Cuccok/kodok/oldtawer')

from ulti.eval.dojo import deal_ulti_biased, deal_parti
from ulti.solvers import pis as pis_bridge
from trickster._solver_core import (solve_root, set_multi_weights, set_multi_cull)
from trickster.games.ulti.game import Rank

N_EACH    = int(sys.argv[1]) if len(sys.argv) > 1 else 150
# Cull-OFF has no pruning → keep the tested positions small (last MAX_CARDS
# tricks), which is exactly where the silent-ulti 7-decision lives. Earlier
# plies are covered by the deterministic cull-off eval reruns.
MAX_CARDS = int(sys.argv[2]) if len(sys.argv) > 2 else 6
TOL = 1e-6


def _is_t7(card, trump):
    return card.suit == trump and card.rank == Rank.SEVEN


def _compare_root(pos):
    """solve_root cull-on vs cull-off; return (n_moves, n_mismatch, max_diff)."""
    set_multi_cull(1)
    von = solve_root(pos, contract='multi')
    set_multi_cull(0)
    voff = solve_root(pos, contract='multi')
    set_multi_cull(1)
    keys = set(von) | set(voff)
    nmis = 0
    maxd = 0.0
    for k in keys:
        a, b = von.get(k), voff.get(k)
        if a is None or b is None:
            nmis += 1
            continue
        d = abs(a - b)
        maxd = max(maxd, d)
        if d > TOL:
            nmis += 1
    return len(keys), nmis, maxd


def _walk_and_test(deal, label, rng, stats):
    """Random walk that never voluntarily plays the trump-7; test every endgame
    ply (<= MAX_CARDS) where the mover still holds it."""
    set_multi_weights(parti_pts=1.0, silent_ulti=2.0)
    hands = [list(deal.sol_hand), list(deal.def1_hand), list(deal.def2_hand)]
    pos = pis_bridge.build_position(
        hands=hands, soloist=0, leader=0, contract='parti',
        trump=deal.trump, talon=list(deal.talon), declare_marriages=True,
    )
    trump = pos.trump
    while not pis_bridge.is_terminal(pos):
        mover = pis_bridge.current_player(pos)
        holds7 = any(_is_t7(c, trump) for c in pos.hands[mover])
        if holds7 and len(pos.hands[mover]) <= MAX_CARDS:
            who = 'sol' if mover == 0 else 'def'
            _, nmis, maxd = _compare_root(pos)
            stats[who + '_plies'] += 1
            stats['total_plies'] += 1
            stats['mismatch'] += nmis
            stats['max_diff'] = max(stats['max_diff'], maxd)
            if nmis:
                print(f"  [MISMATCH] {label} {who}-mover: {nmis} moves differ, "
                      f"max_diff={maxd}", flush=True)
        # advance: random legal move, but keep the trump-7 held if we can
        legal = pis_bridge.legal_actions(pos)
        non7 = [c for c in legal if not _is_t7(c, trump)]
        pis_bridge.apply_move(pos, rng.choice(non7 if non7 else legal))


def main():
    print(f"[cull test] N_EACH={N_EACH}  MAX_CARDS={MAX_CARDS}  "
          f"(value-equiv cull-on vs cull-off, silent_ulti active)", flush=True)
    stats = {'sol_plies': 0, 'def_plies': 0, 'total_plies': 0,
             'mismatch': 0, 'max_diff': 0.0}
    rng = random.Random(12345)
    t0 = time.perf_counter()

    # ulti-biased → soloist holds the 7
    for i in range(N_EACH):
        _walk_and_test(deal_ulti_biased(seed=500_000 + i, alpha=0.6),
                       f"ulti#{i}", rng, stats)
        if (i + 1) % 10 == 0:
            print(f"  ulti {i+1}/{N_EACH} | plies {stats['total_plies']} "
                  f"(sol {stats['sol_plies']}) | mism {stats['mismatch']} | "
                  f"maxd {stats['max_diff']:.1e} | {time.perf_counter()-t0:.0f}s",
                  flush=True)

    # parti filtered to a defender holding the 7. NB: deal cards are
    # ulti.card.Card (rank is the string '7'), NOT trickster Rank.SEVEN —
    # _is_t7 is for trickster GameState cards (pos.hands) only.
    got, i = 0, 0
    while got < N_EACH:
        d = deal_parti(seed=700_000 + i, alpha=0.6)
        i += 1
        if any(c.suit == d.trump and c.rank == '7'
               for c in list(d.def1_hand) + list(d.def2_hand)):
            _walk_and_test(d, f"parti#{got}", rng, stats)
            got += 1
            if got % 10 == 0:
                print(f"  parti {got}/{N_EACH} | def-plies {stats['def_plies']} | "
                      f"mism {stats['mismatch']} | maxd {stats['max_diff']:.1e} | "
                      f"{time.perf_counter()-t0:.0f}s", flush=True)
    wall = time.perf_counter() - t0

    print()
    print(f"positions tested (mover holds trump-7, <= {MAX_CARDS} cards): "
          f"{stats['total_plies']}  (sol-mover {stats['sol_plies']}, "
          f"def-mover {stats['def_plies']})")
    print(f"  move-value mismatches cull-on vs cull-off: {stats['mismatch']}")
    print(f"  max |value diff|: {stats['max_diff']:.2e}   wall={wall:.0f}s")
    print()
    if stats['mismatch'] == 0:
        print("AIRTIGHT: the cull never changes a multi value while silent_ulti "
              "is active — soloist AND defender 7-lines are fully preserved.")
    else:
        print("FAIL: the cull changed a value — investigate.")
    sys.exit(0 if stats['mismatch'] == 0 else 1)


if __name__ == "__main__":
    main()
