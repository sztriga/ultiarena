"""exp46 — is the soloist's rekontra signal calibrated? (Spoiler: game 2d26851c23a2.)

WHAT HAPPENED. milan's AI bid a piros ulti that god confirms WAS makeable, threw it away
on the opening card (only 3 of its 9 legal leads keep the ulti alive), and then — with the
contract already double-dummy dead after trick 1 — REKONTRA'd it, turning −20 into −40.
Re-running the live estimator on that exact position returns **1.000**.

WHY. `apps/api/ai_worker.op_unit_makeability_post1` samples worlds consistent with the
soloist's information and asks, per world, "is this makeable double-dummy?" But
double-dummy lets the soloist tailor its line TO EACH WORLD. It cannot do that in play —
it must choose one line that works across all worlds it cannot distinguish. So the
estimate approaches "makeable in the best case, world by world", which is an upper bound
on realistic makeability, not an estimate of it.

This is the same disease exp27 diagnosed on the other side of the table: the old defender
rule used a blind estimate that read 6–11% where the truth was ~80%, and it wildly
over-kontra'd. exp27 recalibrated the defenders. Nobody ever audited the soloist.

THE MEASUREMENT. Reuse the exp43 corpus — deals already played to terminal by the
deployed stack, with each unit's realised outcome recorded. For every live unit, run the
production estimator at the post-trick-1 position and compare it to what actually
happened. That gives a reliability curve, and the curve gives the correction.

The corpus was generated by the pre-fix (talon-peeking) bidder. That biases WHICH
contracts appear; it does not bias the relationship between an estimate and the outcome
on a given position, which is all this measures.

Run:  WORKERS=6 python3 study.py run
      python3 study.py report
"""
from __future__ import annotations

import json
import os
import sys
import time
from collections import defaultdict
from multiprocessing import get_context

import numpy as np

from ulti.config import apply_deploy_defaults

apply_deploy_defaults()

_HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.join(os.path.dirname(_HERE), "43_kontra_signals", "played.jsonl")
OUT = os.path.join(_HERE, "rekontra.jsonl")
WORKERS = int(os.environ.get("WORKERS", "6"))


def _rung(index):
    from ulti.bidding.ladder import LADDER
    return next(r for r in LADDER if r.index == index)


def _worker(rec):
    """One deal → one row per live unit: (production estimate, realised outcome)."""
    from apps.api import ai_worker
    from ulti.bidding.scorers import resolve_bidset, _play_weights
    from ulti.card import card_from_id
    out = []
    try:
        rung = _rung(rec["rung_index"])
        trump = rec["trump"]
        sol = [card_from_id(i) for i in rec["sol"]]
        bid = resolve_bidset(rung, sol, trump)
        n_trick = int(bid.ulti) + int(bid.durchmars) + int(bid.betli)
        if bid.betli:
            build_c, solve_c, t, restrict, weights = "betli", "betli", None, None, None
        elif bid.durchmars and rung.colorless and n_trick == 1:
            build_c, solve_c, t, restrict, weights = ("durchmars", "durchmars", None,
                                                      None, None)
        else:
            build_c, solve_c, t = "parti", "multi", trump
            restrict = "40" if bid.forty_hundred else ("20" if bid.twenty_hundred else None)
            weights = _play_weights(bid, sol, trump)
        base = {
            "hands0": [rec["sol"], rec["d1"], rec["d2"]], "talon": rec["talon"],
            "build_c": build_c, "solve_c": solve_c, "trump": t, "restrict": restrict,
            "has_ulti": bool(bid.ulti), "weights": weights, "voids": None,
            "history": [tuple(h) for h in rec["hist"][:3]],
        }
        for unit, u in rec["units"].items():
            job = dict(base)
            job.update(unit=unit, viewer=0, seed=rec["seed"] + 200)
            est = ai_worker.op_unit_makeability_post1(job)
            out.append({"seed": rec["seed"], "unit": unit, "contract": rec["contract"],
                        "est": float(est), "made": int(bool(u["made"])),
                        "iso": u["iso"], "trump": trump})
    except Exception as e:
        return [{"seed": rec.get("seed"), "error": f"{type(e).__name__}: {e}"}]
    return out


def _seen():
    s = set()
    if os.path.exists(OUT):
        with open(OUT) as f:
            for line in f:
                try:
                    s.add(json.loads(line)["seed"])
                except Exception:
                    pass
    return s


def run(limit=None):
    seen = _seen()
    deals = []
    with open(CORPUS) as f:
        for line in f:
            try:
                r = json.loads(line)
            except Exception:
                continue
            if r.get("kept") and r["seed"] not in seen:
                deals.append(r)
    if limit:
        deals = deals[:limit]
    print(f"exp46: {len(deals)} deals, {WORKERS} workers", flush=True)
    t0 = time.perf_counter()
    rows = errs = 0
    with get_context("fork").Pool(WORKERS) as pool, open(OUT, "a") as o:
        for i, res in enumerate(pool.imap_unordered(_worker, deals, chunksize=4), 1):
            for r in res:
                o.write(json.dumps(r) + "\n")
                if r.get("error"):
                    errs += 1
                else:
                    rows += 1
            o.flush()
            if i % 50 == 0:
                el = time.perf_counter() - t0
                rate = i / el
                print(f"[rekontra] {i}/{len(deals)}  {el:.0f}s  "
                      f"eta {(len(deals)-i)/rate/60:.1f}m  rows={rows} err={errs}",
                      flush=True)
    print(f"done: {rows} rows, {errs} errors", flush=True)


def report():
    rows = []
    with open(OUT) as f:
        for line in f:
            try:
                r = json.loads(line)
            except Exception:
                continue
            if "error" not in r:
                rows.append(r)
    if not rows:
        print("no rows")
        return
    est = np.array([r["est"] for r in rows])
    made = np.array([r["made"] for r in rows])
    print(f"exp46 — soloist post-trick-1 rekontra signal, {len(rows)} unit-positions\n")
    print(f"overall: mean estimate {est.mean():.3f}   actual make rate {made.mean():.3f}"
          f"   OPTIMISM {est.mean()-made.mean():+.3f}\n")

    print("reliability — is the estimate what it claims to be?")
    print(f"  {'estimate bin':>14s} {'n':>6s} {'mean est':>9s} {'actual':>8s} {'gap':>7s}")
    edges = [0.0, 0.2, 0.4, 0.6, 0.8, 0.95, 1.0001]
    for lo, hi in zip(edges, edges[1:]):
        m = (est >= lo) & (est < hi)
        if m.sum() < 5:
            continue
        print(f"  {f'[{lo:.2f},{hi:.2f})':>14s} {int(m.sum()):6d} {est[m].mean():9.3f} "
              f"{made[m].mean():8.3f} {est[m].mean()-made[m].mean():+7.3f}")

    print("\nthe dangerous cell — estimate says CERTAIN:")
    m = est >= 0.95
    if m.sum():
        print(f"  n={int(m.sum())}  actually made {100*made[m].mean():.1f}%  "
              f"→ {int((~made[m].astype(bool)).sum())} rekontras on contracts that FAILED")

    print("\nby unit:")
    print(f"  {'unit':12s} {'n':>6s} {'mean est':>9s} {'actual':>8s} {'optimism':>9s}")
    by = defaultdict(list)
    for r in rows:
        by[r["unit"]].append(r)
    for u, rs in sorted(by.items(), key=lambda kv: -len(kv[1])):
        e = np.array([x["est"] for x in rs])
        a = np.array([x["made"] for x in rs])
        print(f"  {u:12s} {len(rs):6d} {e.mean():9.3f} {a.mean():8.3f} "
              f"{e.mean()-a.mean():+9.3f}")

    # What the deployed rule does with this, in GP. Rekontra fires when the soloist's
    # no-kontra EV is positive at the estimate; the realised cost is the level-1 vs
    # level-2 difference on the deals where it fired.
    print("\nrekontra decision at the deployed threshold (sol_ev(est) > 0):")
    from ulti.bidding.kontra import _sol_ev
    from ulti.bidding.ladder import BidSet
    fired = bad = 0
    delta = 0.0
    for r in rows:
        iso = r["iso"]
        # a symmetric proxy bid is enough to locate the threshold; the GP itself comes
        # from the recorded per-level isolated payoffs, which are exact
        b = BidSet(ulti=(r["unit"] == "ulti"), betli=(r["unit"] == "betli"),
                   durchmars=(r["unit"] == "durchmars"))
        if _sol_ev(r["est"], b, 0) > 0:
            fired += 1
            delta += iso[2] - iso[1]
            if not r["made"]:
                bad += 1
    if fired:
        print(f"  fires on {fired}/{len(rows)} ({100*fired/len(rows):.0f}%) of kontra'd "
              f"units; {bad} ({100*bad/fired:.0f}%) of those had already FAILED")
        print(f"  mean soloist GP swing from rekontra-ing, over the units it fires on: "
              f"{delta/fired:+.2f}")

    # ── what SHOULD the threshold be? ────────────────────────────────────────────
    # Conditional on the unit having been kontra'd, the soloist gets iso[1] by declining
    # and iso[2] by rekontra-ing. That makes the optimal policy computable exactly from
    # the recorded payoffs — no model, no assumption about calibration.
    #
    # The theory says rekontra iff P(make) > 0.5 for EVERY contract (the level-1 vs
    # level-2 comparison; even bid-ulti's asymmetric bukott breaks even at one half).
    # The DEPLOYED rule instead asks "is my no-kontra EV positive", which for a bid ulti
    # means p > 0.667 — conservative by construction. Whether that accidentally offsets
    # the estimator's optimism is an empirical question, and this is the answer.
    print("\nthreshold sweep — soloist GP per kontra'd unit (iso[2] if fire else iso[1]):")
    est = np.array([r["est"] for r in rows])
    iso1 = np.array([r["iso"][1] for r in rows], dtype=float)
    iso2 = np.array([r["iso"][2] for r in rows], dtype=float)
    print(f"  {'policy':>22s} {'fires':>7s} {'GP/unit':>9s}")
    print(f"  {'never rekontra':>22s} {'0%':>7s} {iso1.mean():+9.3f}")
    print(f"  {'always rekontra':>22s} {'100%':>7s} {iso2.mean():+9.3f}")
    best = None
    for tau in np.linspace(0.0, 1.0, 51):
        fire = est > tau
        gp = float(np.where(fire, iso2, iso1).mean())
        if best is None or gp > best[1]:
            best = (float(tau), gp, float(fire.mean()))
    dep = np.array([_sol_ev(r["est"],
                            BidSet(ulti=(r["unit"] == "ulti"),
                                   betli=(r["unit"] == "betli"),
                                   durchmars=(r["unit"] == "durchmars")), 0) > 0
                    for r in rows])
    print(f"  {'DEPLOYED (sol_ev>0)':>22s} {100*dep.mean():6.0f}% "
          f"{float(np.where(dep, iso2, iso1).mean()):+9.3f}")
    theory = est > 0.5
    print(f"  {'theory (p>0.5)':>22s} {100*theory.mean():6.0f}% "
          f"{float(np.where(theory, iso2, iso1).mean()):+9.3f}")
    print(f"  {'swept optimum':>22s} {100*best[2]:6.0f}% {best[1]:+9.3f}"
          f"   (est > {best[0]:.2f})")

    print("\n  per-unit swept optimum:")
    for u, rs in sorted(by.items(), key=lambda kv: -len(kv[1])):
        e = np.array([x["est"] for x in rs])
        i1 = np.array([x["iso"][1] for x in rs], dtype=float)
        i2 = np.array([x["iso"][2] for x in rs], dtype=float)
        d = np.array([_sol_ev(x["est"],
                              BidSet(ulti=(u == "ulti"), betli=(u == "betli"),
                                     durchmars=(u == "durchmars")), 0) > 0 for x in rs])
        b = max(((t, float(np.where(e > t, i2, i1).mean())) for t in np.linspace(0, 1, 51)),
                key=lambda kv: kv[1])
        print(f"    {u:12s} n={len(rs):4d}  deployed {float(np.where(d, i2, i1).mean()):+7.2f}"
              f"   best {b[1]:+7.2f} at est>{b[0]:.2f}"
              f"   gain {b[1]-float(np.where(d, i2, i1).mean()):+6.2f}")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "report"
    if cmd == "run":
        run(int(sys.argv[2]) if len(sys.argv) > 2 else None)
    elif cmd == "report":
        report()
    else:
        raise SystemExit(f"unknown command {cmd!r}")


if __name__ == "__main__":
    main()
